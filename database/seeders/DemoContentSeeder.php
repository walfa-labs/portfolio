        $series = $this->seedWritingSeries();

        $this->seedWorkExperiences($tagIds);
        $this->seedEducations($tagIds);
        $this->seedCertifications($tagIds);
        $this->seedPublications($tagIds);
        $this->seedProjects($tagIds);
        $this->seedAwards($tagIds);
        $this->seedWritings($tagIds, $series);

        $this->seedMedia();
    }

    /**
     * Create the writing series and return their ids keyed by slug.
     *
     * @return array<string, int>
     */
    private function seedWritingSeries(): array
    {
        $series = [];

        foreach (self::WRITING_SERIES as $row) {
            $slug = ContentSlug::canonicalize($row['title']);
            $series[$slug] = WritingSeries::query()
                ->updateOrCreate(['slug' => $slug], ['title' => $row['title'], 'description' => $row['description']])
                ->getKey();
        }

        return $series;
    }

