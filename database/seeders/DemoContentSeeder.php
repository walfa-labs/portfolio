    /**
     * Attach the generated media the demo corpus carries (§9.1, §9.9).
     *
     * No binary is fetched and none is committed: each collection is drawn from
     * the item's own key, written to the storage disk, and then pushed through
     * the *same* {@see GenerateMediaVariants} job a production upload
     * dispatches, so a seeded row reaches `processed` with the variant map the
     * pipeline builds rather than a hand-written one. Because the generator
     * seeds its RNG from `crc32($itemKey)`, re-seeding redraws byte-identical
     * files (§9.9).
     *
     * `awards` carry no media in v1 (§2.10). Two collections are deliberately
     * left unseeded: a writing's `inline` images and a publication's `pdf`.
     * Both stand in for authored content the demo corpus has none of, and a
     * placeholder would only add a dead in-body image or download link.
     *
     * The pass runs only when both disks it writes to answer
     * ({@see self::diskAnswers()}); a corpus whose images are half-written is
     * worse than one that says why it has none.
     */
    private function seedMedia(): void
    {
        foreach (self::MEDIA_DISKS as $disk) {
            if ($this->diskAnswers($disk)) {
                continue;
            }

            $this->command->warn(
                "Media seeding skipped: the [{$disk}] disk did not answer. Check `storage:ensure-bucket` and the AWS_* settings.",
            );

            return;
        }

        $this->seedOwnerMedia();

        $this->seedProjectMedia(Project::query()->orderBy('id')->get());
        $this->seedWritingMedia(Writing::query()->where('status', ContentStatus::Published)->orderBy('id')->get());
        $this->seedLogoMedia(WorkExperience::query()->orderBy('id')->get());
        $this->seedLogoMedia(Education::query()->orderBy('id')->get());
        $this->seedBadgeMedia(Certification::query()->orderBy('id')->get());
    }

    /**
     * Whether a disk answers at all, so the media pass can be skipped cleanly.
     *
     * A `HEAD` on a path that cannot exist is the cheapest reachability check
     * the S3 driver offers: it answers `false` for a bucket that exists and
     * throws for one that does not — a missing bucket, a wrong endpoint, no
     * credentials. Seeding is the wrong place to discover that, because the
     * pass is not transactional: aborting half-way leaves content rows with no
     * media and a trail of `failed` rows. The pass is therefore skipped as a
     * unit, with the reason named, rather than attempted and abandoned.
     */
    private function diskAnswers(string $disk): bool
    {
        try {
            Storage::disk($disk)->exists('reachability-probe');

            return true;
        } catch (Throwable $exception) {
            report($exception);

            return false;
        }
    }

    /**
     * Attach the owner's avatar and CV to the administrator (§9.1).
     *
     * The owner is the `User` {@see AdministratorSeeder} creates, so it is
     * looked up through the same config key that seeder keys it on: the admin
     * seeder stays the one place that decides who the owner is, and a run of
     * this seeder alone attaches nothing rather than inventing an account.
     */
    private function seedOwnerMedia(): void
    {
        $owner = User::query()->where('email', (string) config('portfolio.admin.email'))->first();

        if ($owner === null) {
            return;
        }

        $this->storeMedia(
            $owner,
            'avatar',
            PlaceholderImage::bytes($this->itemKey($owner, 'avatar'), 512, 512, 'jpg'),
            alt: null,
            width: 512,
            height: 512,
        );

        $this->storeMedia(
            $owner,
            'cv',
            $this->placeholderPdf('Curriculum vitae'),
            alt: 'A placeholder curriculum vitae - replace it with the real one.',
        );
    }

    /**
     * Attach a cover and two to four screenshots to every project (§9.1).
     *
     * The cover is the one collection whose variant set depends on the
     * mediable: the job adds the `1200x630` `og_image` size to a *writing's*
     * cover and never to a project's (§9.5), so `cover_1200x630.*` must not
     * appear under a project.
     *
     * @param  Collection<int, Project>  $projects
     */
    private function seedProjectMedia(Collection $projects): void
    {
        $screenshotLimit = (int) config('media.collections.screenshot.max_items', 8);

        foreach ($projects->values() as $index => $project) {
            $this->storeMedia(
                $project,
                'cover',
                PlaceholderImage::bytes($this->itemKey($project, 'cover'), 1600, 900),
                alt: 'Cover of '.$project->title,
                width: 1600,
                height: 900,
            );

            $screenshots = min($screenshotLimit, 2 + ($index % 3));

            for ($number = 1; $number <= $screenshots; $number++) {
                $this->storeMedia(
                    $project,
                    'screenshot',
                    PlaceholderImage::bytes($this->itemKey($project, 'screenshot', $number), 1600, 900),
                    alt: 'Screenshot '.$number.' of '.$project->title,
                    sortOrder: $number,
                    width: 1600,
                    height: 900,
                );
            }
        }
    }

    /**
     * Attach a cover to every published writing (§9.1).
     *
     * A draft keeps no cover: nothing public renders one (§3.1), and a
     * writing's cover is the authored-content case §9.6 requires an `alt` for,
     * so a placeholder on an unreachable row would be noise. This cover is also
     * where `writings.og_image_path` comes from — the job's `1200x630` variant
     * is the size that column points at (§9.5).
     *
     * @param  Collection<int, Writing>  $writings
     */
    private function seedWritingMedia(Collection $writings): void
    {
        foreach ($writings as $writing) {
            $this->storeMedia(
                $writing,
                'cover',
                PlaceholderImage::bytes($this->itemKey($writing, 'cover'), 1600, 900),
                alt: 'Cover of '.$writing->title,
                width: 1600,
                height: 900,
            );
        }
    }

    /**
     * Attach one SVG logo to every work-experience and education entry (§9.1).
     *
     * The logo is vector: it is stored as authored and never rasterised, so the
     * job recognises `image/svg+xml` and writes an empty variant map (§9.5).
     * Its `alt` stays `NULL`, which §9.2 permits for `logo` and which leaves
     * §7.8's deterministic `"{Employer name} logo"` rule to the renderer.
     *
     * The parameter is a template rather than `WorkExperience|Education`
     * because a `Collection`'s value type is invariant: a caller passing
     * `Collection<int, WorkExperience>` would not satisfy a union annotation.
     *
     * @template TEntry of Model
     *
     * @param  Collection<int, TEntry>  $entries
     */
    private function seedLogoMedia(Collection $entries): void
    {
        foreach ($entries as $entry) {
            $this->storeMedia(
                $entry,
                'logo',
                $this->placeholderSvg($this->itemKey($entry, 'logo')),
                alt: null,
            );
        }
    }

    /**
     * Attach a badge to every certification (§9.1).
     *
     * `alt` stays `NULL` for the same reason it does on a logo (§9.2): §7.8
     * gives a badge a deterministic rule and the badge is only named when it is
     * a link.
     *
     * @param  Collection<int, Certification>  $certifications
     */
    private function seedBadgeMedia(Collection $certifications): void
    {
        foreach ($certifications as $certification) {
            $this->storeMedia(
                $certification,
                'badge',
                PlaceholderImage::bytes($this->itemKey($certification, 'badge'), 512, 512),
                alt: null,
                width: 512,
                height: 512,
            );
        }
    }

    /**
     * Write one media row's generated bytes to the disk and run the pipeline.
     *
     * The bytes go to the disk first, then the row is created, then the *same*
     * {@see GenerateMediaVariants} job an admin upload dispatches runs
     * synchronously — so the row ends up `processed` with the variant map the
     * job builds, and the seeded path is not a shortcut around the pipeline
     * (§9.9). The object path and the disk follow the upload controller: the
     * content-addressed `{alias}s/{sha256}/original.{ext}` layout (§9.4), and
     * `s3-private` for the one private collection, `cv` (§9.3).
     *
     * A single-cardinality collection replaces whatever is already attached to
     * the `(mediable, collection)` pair — the controller's rule (§9.1) — and a
     * `many` collection replaces only the row holding the same bytes, so
     * re-seeding adds no duplicates. Both paths delete through the model, so
     * the replaced row's objects leave the disk with it (§9.8).
     *
     * @param  string  $contents  The generated bytes, written verbatim.
     * @param  string|null  $alt  `NULL` for the collections §7.8 names deterministically (§9.2).
     * @param  int  $sortOrder  The display order within a `many` collection.
     * @param  int|null  $width  The original's width, or `NULL` for a vector or a PDF.
     * @param  int|null  $height  The original's height, or `NULL` for a vector or a PDF.
     */
    private function storeMedia(
        Model $mediable,
        string $collection,
        string $contents,
        ?string $alt,
        int $sortOrder = 0,
        ?int $width = null,
        ?int $height = null,
    ): void {
        $alias = $mediable->getMorphClass();
        $disk = $collection === 'cv' ? 's3-private' : 's3';
        $mimeType = (string) (new finfo(FILEINFO_MIME_TYPE))->buffer($contents);
        $extension = self::EXTENSIONS[$mimeType] ?? 'bin';
        $sha256 = hash('sha256', $contents);
        $path = $alias.'s/'.$sha256.'/original.'.$extension;

        $this->replaceMedia($mediable, $collection, $sha256);

        Storage::disk($disk)->put($path, $contents);

        $media = Media::create([
            'mediable_type' => $alias,
            'mediable_id' => $mediable->getKey(),
            'collection' => $collection,
            'disk' => $disk,
            'path' => $path,
            'original_name' => 'original.'.$extension,
            'mime_type' => $mimeType,
            'alt' => $alt,
            'size' => strlen($contents),
            'width' => $width,
            'height' => $height,
            'sha256' => $sha256,
            'variants' => null,
            'status' => 'pending',
            'sort_order' => $sortOrder,
        ]);

        GenerateMediaVariants::dispatchSync($media);
    }

    /**
     * Delete the rows a re-seed replaces, so their objects leave the disk too.
     *
     * Rows are deleted one at a time through the model rather than by the query
     * builder: `Media::deleting()` is what removes the original and every
     * variant object, honouring the shared-object rule (§9.4, §9.8).
     */
    private function replaceMedia(Model $mediable, string $collection, string $sha256): void
    {
        $query = Media::query()
            ->where('mediable_type', $mediable->getMorphClass())
            ->where('mediable_id', $mediable->getKey())
            ->where('collection', $collection);

        if (! $this->isSingleCardinality($collection)) {
            $query->where('sha256', $sha256);
        }

        $query->get()->each(fn (Media $previous): bool => $previous->delete());
    }

    /**
     * Whether a collection's upload replaces the previous row (§9.1).
     */
    private function isSingleCardinality(string $collection): bool
    {
        return (string) config("media.collections.{$collection}.cardinality", 'many') === 'single';
    }

    /**
     * The deterministic generator key for one item's collection (§9.9).
     *
     * `PlaceholderImage` seeds its RNG from `crc32($itemKey)`, so this key is
     * what makes the bytes reproducible. It is built from the row's slug — the
     * identity the content seeders `updateOrCreate` on, so it survives a
     * re-seed — and falls back to the row's key for a model that has no slug.
     */
    private function itemKey(Model $mediable, string $collection, ?int $index = null): string
    {
        $slug = $mediable->getAttribute('slug');

        $key = $mediable->getMorphClass().':'.($slug === null ? $mediable->getKey() : (string) $slug).':'.$collection;

        return $index === null ? $key : $key.':'.$index;
    }

    /**
     * Build the inline SVG logo for one entry (§9.1, §9.9).
     *
     * SVG is stored as authored and is never rasterised (§9.5), so the mark is
     * written straight to the disk and recorded as `image/svg+xml`. It is drawn
     * from `crc32($itemKey)` so re-seeding redraws the same mark, and it
     * carries no script, no event handler and no external reference — which is
     * all §9.6's sanitiser exists to strip, and the reason this generated
     * document needs no pass through it.
     */
    private function placeholderSvg(string $itemKey): string
    {
        $seed = abs(crc32($itemKey));
        $primary = self::SVG_PRIMARY[$seed % count(self::SVG_PRIMARY)];
        $squareX = 40 + $seed % 96;
        $squareY = 40 + intdiv($seed, 7) % 96;
        $circleX = 40 + intdiv($seed, 11) % 160;
        $circleY = 40 + intdiv($seed, 13) % 160;
        $radius = 24 + intdiv($seed, 17) % 24;

        return <<<SVG
            <svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" role="img">
              <rect width="256" height="256" fill="#F6F5F0"/>
              <rect x="{$squareX}" y="{$squareY}" width="96" height="96" fill="{$primary}" stroke="#111111" stroke-width="2"/>
              <circle cx="{$circleX}" cy="{$circleY}" r="{$radius}" fill="#F5C948" stroke="#111111" stroke-width="2"/>
              <rect x="1" y="1" width="254" height="254" fill="none" stroke="#111111" stroke-width="2"/>
            </svg>
            SVG;
    }

    /**
     * Build a minimal, valid, byte-stable PDF (§9.1, §9.9).
     *
     * `cv` accepts `application/pdf` only, and the job re-checks that the
     * stored bytes open with `%PDF-` before it will mark the row processed
     * (§9.6), so the seeder writes a genuine one-page document rather than a
     * stub. Nothing in it varies between runs — no `/CreationDate`, no `/ID` —
     * which is what keeps the seeded bytes identical across re-seeds.
     */
    private function placeholderPdf(string $title): string
    {
        $stream = 'BT /F1 20 Tf 72 770 Td ('.$this->pdfText($title).') Tj ET'."\n"
            .'BT /F1 12 Tf 72 740 Td (Placeholder document - replace it with the real one.) Tj ET';

        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
            '<< /Length '.strlen($stream)." >>\nstream\n".$stream."\nendstream",
        ];

        $document = "%PDF-1.4\n";
        $offsets = [];

        foreach ($objects as $index => $body) {
            $offsets[] = strlen($document);
            $document .= ($index + 1)." 0 obj\n".$body."\nendobj\n";
        }

        $startxref = strlen($document);
        $size = count($objects) + 1;

        $document .= "xref\n0 {$size}\n0000000000 65535 f \n";

        foreach ($offsets as $offset) {
            $document .= str_pad((string) $offset, 10, '0', STR_PAD_LEFT)." 00000 n \n";
        }

        return $document."trailer\n<< /Size {$size} /Root 1 0 R >>\nstartxref\n".$startxref."\n%%EOF\n";
    }

    /**
     * Escape a string for a PDF literal string (§7.3.4.2).
     */
    private function pdfText(string $value): string
    {
        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $value);
    }

    /**
     * Build the shared columns for one seeded content row.
     *
     * The slug is derived from the title via {@see ContentSlug::canonicalize()},
     * matching what `HasSlug` stores on create, so the `updateOrCreate` lookup
     * key and the persisted value can never disagree.
     *
     * @param  array<string, mixed>  $attributes  The per-type columns, merged last.
     * @return array<string, mixed>
     */
    private function contentRow(string $slug, string $title, bool $published, array $attributes): array
    {
        return [
            'slug' => ContentSlug::canonicalize($title),
            'title' => $title,
            'summary' => fake()->sentence(14),
            'body' => fake()->paragraphs(3, true),
            'status' => $published ? ContentStatus::Published : ContentStatus::Draft,
            'published_at' => $published ? fake()->dateTimeBetween('-18 months', 'now') : null,
            'is_placeholder' => true,
            ...$attributes,
        ];
    }

    /**
     * Create the rows and attach two to four seeded tags to each of them.
     *
     * @param  class-string<WorkExperience|Education|Certification|Publication|Project|Award|Writing>  $modelClass
     * @param  array<int, array<string, mixed>>  $rows
     * @param  Collection<int, int>  $tagIds
     */
    private function createContentRows(string $modelClass, array $rows, Collection $tagIds): void
    {
        foreach ($rows as $index => $row) {
            $model = $modelClass::query()->updateOrCreate(['slug' => $row['slug']], $row);

            if ($tagIds->isNotEmpty()) {
                $model->tags()->sync($this->tagsFor($tagIds, $index));
            }
        }
    }

    /**
     * Pick two to four distinct tags for the row at the given index.
     *
     * The stride walks the whole vocabulary, so consecutive rows share tags with
     * rows of other types — that is what puts a project and a writing on the
     * same tag page (SC-4).
     *
     * @param  Collection<int, int>  $tagIds
     * @return array<int, int>
     */
    private function tagsFor(Collection $tagIds, int $index): array
    {
        $count = min($tagIds->count(), 2 + ($index % 3));
        $picked = [];

        for ($offset = 0; $offset < $count; $offset++) {
            $picked[] = $tagIds[($index * 3 + $offset) % $tagIds->count()];
        }

        return $picked;
    }

    /**
     * Build a plausible Markdown article body.
     *
     * Only the Markdown source is stored; `body_html` and
     * `reading_time_minutes` are derived by the model on save (§2.3).
     */
    private function markdownBody(): string
    {
        return implode("\n\n", [
            '## '.rtrim(fake()->sentence(4), '.'),
            fake()->paragraph(6),
            '- '.implode("\n- ", (array) fake()->sentences(3)),
            '## '.rtrim(fake()->sentence(5), '.'),
            fake()->paragraph(5),
        ]);
    }
